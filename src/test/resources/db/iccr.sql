-- Test schema and data for the ICCR (Infection Control) report tables (H2 in Oracle mode): IccrRepositoriesTest
-- and IccrDocWriteTest. Document 100 has four tests: a viral load (VL) with a result code used by two test
-- types (DET, listed once per name, as before), a test with codes that are not in the code lists, and the
-- same CD4 test entered twice (the table has no key).

