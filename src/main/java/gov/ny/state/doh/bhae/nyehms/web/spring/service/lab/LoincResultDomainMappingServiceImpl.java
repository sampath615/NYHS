	@Override
	public void addNewLabLoincDetailsToLookup(BindingResult bindingResult, UserObject userObject, String loincCode, String testTypeCode){
		String transactionMessage=null;
		Integer statusCode;
		
		Map<Object, Object> inOutParameterMap = new HashMap<Object, Object>();
		inOutParameterMap.put("loincCode", loincCode);
		inOutParameterMap.put("testTypeCode", testTypeCode);
		
		int resultCount = loincResultDomainMappingDAO.addNewLabLoincDetailsToLookup(inOutParameterMap);
		
		if(resultCount > 0){
			transactionMessage = "Successfully added new LOINC code details.";
			statusCode = 0;
		}else{
			transactionMessage = "Unable to add the LOINC code details, please contact helpline.";
			statusCode = -1;
		}
		
		commonExceptionHandler.inspectDBTransacionResult(statusCode, transactionMessage, bindingResult);
		
		
	}
	
	@Override
	public int addNewAcceptableTestResults(AcceptedTestResultDomainVO acceptedTestResultDomainVO, BindingResult bindingResult, UserObject userObject){
		
		Map<Object, Object> inOutParameterMap = new HashMap<Object, Object>();
		inOutParameterMap.put("typeOfResult", acceptedTestResultDomainVO.getTypeOfResult());
		inOutParameterMap.put("acceptedValue", acceptedTestResultDomainVO.getAcceptedValue());
		inOutParameterMap.put("rangeLowerBound", acceptedTestResultDomainVO.getRangeLowerBound());
		inOutParameterMap.put("rangeUpperBound", acceptedTestResultDomainVO.getRangeUpperBound());
		inOutParameterMap.put("lastUpdatedBy", userObject.getWorkerId());
		
		
		loincResultDomainMappingDAO.addNewAcceptableTestResults(inOutParameterMap);
		
		BigDecimal _value = (BigDecimal)inOutParameterMap.get("autoGeneratedId");
		int attributeDomainId =  _value.intValue();
		
		
		if(attributeDomainId == 0){
			throw new DataRetrievalFailureException("Failed to add new Test results, please contact helpline."); 
		}
		
		return attributeDomainId;
		
		
		
		
		
	}
	
