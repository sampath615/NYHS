	@Override
	public int assoicateTestResultsToLoincCode(String loincCode, int attributeDomainId, String standardResults, BindingResult bindingResult, UserObject userObject ){
		
		String transactionMessage = null;
		Integer statusCode;
				
		Map<Object, Object> inOutParameterMap = new HashMap<Object, Object>();
		inOutParameterMap.put("loincCode", loincCode);
		inOutParameterMap.put("attributeDomainId", attributeDomainId);
		inOutParameterMap.put("standardResults", standardResults);
		inOutParameterMap.put("lastUpdatedBy", userObject.getWorkerId());
		
		int resultCount = loincResultDomainMappingDAO.assoicateTestResultsToLoincCode(inOutParameterMap);
		
		if(resultCount > 0){
			transactionMessage = "Successfully associated the Test Results to the LOINC code "+loincCode;
			statusCode = 0;
		}else{
			transactionMessage = "Failed to assocate the Test Results to the LOINC code, please contact help line.";
			statusCode = -1;
		}
		if(statusCode != 0){
			throw new DataRetrievalFailureException(transactionMessage);
		}
	
		commonExceptionHandler.inspectDBTransacionResult(statusCode, transactionMessage, bindingResult);
		
		return statusCode;
	}
	
