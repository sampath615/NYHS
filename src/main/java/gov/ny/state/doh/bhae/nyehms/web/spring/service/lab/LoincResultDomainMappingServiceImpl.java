	@Override
	public void addNewAcceptableTestResultsAndAssociateToLoincCode(AcceptedTestResultDomainVO acceptedTestResultDomainVO, BindingResult bindingResult, UserObject userObject){
		String transactionMessage = null;
		boolean isError = false; 
		try{
			labReportsTransactionHelper.addNewAcceptableTestResultsAndAssociateToLoincCode(acceptedTestResultDomainVO, bindingResult, userObject);
		}catch(DataAccessException dataAccessException){
			isError = true;
			transactionMessage = dataAccessException.getMessage();
			log.error("Failed to associate the Test Results to the LOINC code  {}",transactionMessage);
		}catch(Exception exception){
			isError = true;
			log.error("Failed to associate the Test Results to the LOINC code  {}",exception.getMessage());
			transactionMessage = "Failed to associate the Test Results to the LOINC code, please contact helpline.";
		}
		
		if(isError){
			commonExceptionHandler.inspectDBTransacionResult(-1, transactionMessage, bindingResult);
		}
	}
	
	
