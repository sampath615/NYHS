	@Override
	public void changeLoincMultiSpotDocuments(Integer[] documentIds, String documentType,
			int rawDocumentEditedProcessStatus, BindingResult bindingResult, UserObject userObject) {
		
		boolean isError = false; 
		try{
			
			Map<String, Integer[]> inputParameterMap = new HashMap<String, Integer[]>();
			inputParameterMap.put("documentIds", documentIds);
			
			int resultCount = loincResultDomainMappingDAO.verifyForMayoLabDocuments(inputParameterMap);
			
			if(resultCount > 0) {
				commonExceptionHandler.inspectDBTransacionResult(-1, "Please check the selected documents, it has to be Mayo lab and loinc code should be 81641-3", bindingResult);
				return;
			}
						
			labReportsTransactionHelper.changeLoincMultiSpotDocuments(documentIds, bindingResult,userObject);
		}catch(DataAccessException dataAccessException){
			isError = true;
			log.error("Failed to update the loinc for the selected Documents "+documentIds);
			log.error(dataAccessException.getMessage());
		}catch(Exception exception){
			isError = true;
			log.error("Failed to update the loinc for the selected Documents "+documentIds);
			log.error(exception.getMessage());
		}
		
		if(isError || bindingResult.hasErrors()){
			commonExceptionHandler.inspectDBTransacionResult(-1, "Failed to update the Loinc, Please contact helpline.", bindingResult);
		}else{
			commonExceptionHandler.inspectDBTransacionResult(0, "Successfully updated with Loinc(30361-0)", bindingResult);
		}
		
		
	}
