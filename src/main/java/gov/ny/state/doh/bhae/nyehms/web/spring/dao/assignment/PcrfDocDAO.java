	/**
	 * One insert of several RAW_PCRF_DETAILS rows: DOCUMENT_ID, PCRF_SECTION and the given attributes of each element.
	 *
	 * @param dateIndex the position (0-based) of the value that went through FN_TO_DATE(x, 'MM/DD/YYYY'), or -1
	 */
	@SuppressWarnings("unchecked")
	private void details(Map<String, Object> map, String listKey, String attributes, Function<PcrfSubstanceDocVO, List<Object>> values,
			int dateIndex) {
		List<PcrfSubstanceDocVO> list = (List<PcrfSubstanceDocVO>) map.get(listKey);
		if (list == null || list.isEmpty()) {
			// the former SQL insert had no rows to insert and failed
			throw new InvalidDataAccessResourceUsageException("No rows in " + listKey + " to insert into RAW_PCRF_DETAILS");
		}
		Object documentId = Values.longValue(map.get("DOCUMENT_ID"));
		Object section = typed(STRING, Values.text(map.get("PCRF_SECTION")));
		List<Object> parameters = new ArrayList<>();
		List<String> rows = new ArrayList<>();
		for (PcrfSubstanceDocVO element : list) {
			List<String> row = new ArrayList<>();
			parameters.add(documentId);
			row.add("?" + parameters.size());
			parameters.add(section);
			row.add("?" + parameters.size());
			List<Object> elementValues = values.apply(element);
			for (int i = 0; i < elementValues.size(); i++) {
				parameters.add(elementValues.get(i));
				// FN_TO_DATE is the database's function; its DATE is assigned as a timestamp (the same value)
				row.add(i == dateIndex ? "cast(FN_TO_DATE(?" + parameters.size() + ", 'MM/DD/YYYY') as Timestamp)" : "?" + parameters.size());
			}
			rows.add("(" + String.join(", ", row) + ")");
		}
		jpql.update("insert into RawPcrfDetails (documentId, pcrfSection, " + attributes + ") values " + String.join(", ", rows),
				parameters.toArray());
	}

	private static Long documentKey(String docId) {
		return Values.longValue(docId);
	}
