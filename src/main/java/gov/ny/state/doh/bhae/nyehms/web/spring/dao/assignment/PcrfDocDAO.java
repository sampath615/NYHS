	/** The select list of getRawPCRFDoc: each JPQL expression under its VO property's name. */
	private static final String READ_SELECT = Arrays.stream(READ).map(c -> c[1] + " as " + c[0]).collect(Collectors.joining(", "));

	/**
	 * A form with the person it is matched to (MATCHED_STATENO) and the date it was imported to eHARS (EHARS_IMPORT_DATE,
	 * MM/DD/YYYY).
	 *
	 * @return the form, or null if there is none
	 */
	public RawAcrfDocVO getRawPCRFDoc(String documentId) throws DataAccessException {
		return jpql.one("select " + READ_SELECT + " from RawPcrfDoc rw"
				+ " left join StdPcrfDoc std on std.documentId = rw.documentId"
				+ " left join PersonDocAssociation pdoc on pdoc.documentId = rw.documentId"
				+ " where pdoc.dissassociationDate is null and rw.documentId = ?1",
				Rows.bean(RawAcrfDocVO.class), AcrfDocDAO.documentKey(documentId));
	}

