	/** The select list of getRawACRFDoc: each JPQL expression under its VO property's name. */
	private static final String READ_SELECT = Arrays.stream(READ).map(c -> c[1] + " as " + c[0]).collect(Collectors.joining(", "));

	/**
	 * A form with the person it is matched to (STATENO of its active association, MATCHED_STATENO) and the date it was
	 * imported to eHARS (EHARS_IMPORT_DATE, MM/DD/YYYY).
	 *
	 * @return the form, or null if there is none
	 */
	public RawAcrfDocVO getRawACRFDoc(String documentId) throws DataAccessException {
		return jpql.one("select " + READ_SELECT + " from RawAcrfDoc rw"
				+ " left join StdAcrfDoc std on std.documentId = rw.documentId"
				+ " left join PersonDocAssociation pdoc on pdoc.documentId = rw.documentId and pdoc.dissassociationDate is null"
				+ " where rw.documentId = ?1", Rows.bean(RawAcrfDocVO.class), documentKey(documentId));
	}

	/** Inserts a form (DOCUMENT_ID from the VO). */
	@Transactional
	public void addRawACRFDoc(RawAcrfDocVO rawAcrfDoc) throws DataAccessException {
		CrfColumns.insert(jpql, "RawAcrfDoc", INSERT, rawAcrfDoc);
	}

	/** Changes a form (DOCUMENT_ID from the VO); nothing happens if there is no such form. */
	@Transactional
	public void updateRawACRFDoc(RawAcrfDocVO rawAcrfDoc) throws DataAccessException {
		CrfColumns.update(jpql, "RawAcrfDoc", UPDATE, rawAcrfDoc, "e.documentId = ?%d", CrfColumns.typed(INTEGER, rawAcrfDoc.getDocumentId()));
	}

	/** The ARV use types not ended (END_DATE null or after now), in no particular order. */
	public List<String> getArvUserTypeList() {
		return jpql.list("select a.arvUseType from CodedAcrfArvs a where a.endDate is null or a.endDate > sysdate", Rows.scalar(String.class));
	}

	/**
	 * The name, last-name soundex and date of birth (MM/DD/YYYY) of an eHARS person by state number, from any one of
	 * its rows whose status is not D, M or P.
	 *
	 * @return the person (fname, mname, lname, lastnameSoundex, dateOfBirth), or null
	 */
	public RawAcrfDocVO getAcrfFormDataFromAcrf(String stateNo) {
		return jpql.one("select m.firstName as fname, m.middleName as mname, m.lastName as lname, soundex(m.lastName) as lastnameSoundex,"
				+ " to_char(FN_TO_DATE(m.dob, 'MM/DD/YYYY'), 'MM/DD/YYYY') as dateOfBirth"
				+ " from NyehmsEharsStatenoMap m where m.nyehmsStateno = ?1 and coalesce(m.statusFlag, 'XX') not in ('D', 'M', 'P') limit 1",
				Rows.bean(RawAcrfDocVO.class), stateNo);
	}

	/** The DOCUMENT_ID a caller's text stands for (Oracle compared the number column with the text as a number). */
	static Integer documentKey(String documentId) {
		return documentId == null ? null : new java.math.BigDecimal(documentId.trim()).intValueExact();
	}
